# ==========================================
# Helper Evaluation Function (Fixed for zeros)
# ==========================================
def evaluate_forecasts(actual, predicted, model_name):
    rmse = np.sqrt(mean_squared_error(actual, predicted))
    mae = mean_absolute_error(actual, predicted)

    # Safe MAPE calculation handling potential 0 values in temperature
    actual_safe = np.where(actual == 0, 1e-5, actual)
    mape = np.mean(np.abs((actual - predicted) / actual_safe)) * 100
    r2 = r2_score(actual, predicted)

    print(f"--- Metrics for {model_name} on Validation Set ---")
    print(f"RMSE: {rmse:.4f} | MAE: {mae:.4f} | MAPE: {mape:.4f}% | R²: {r2:.4f}\n")

    plt.figure(figsize=(7, 4))
    plt.plot(actual.index, actual, label='Actual Values', color='black')
    plt.plot(actual.index, predicted, label='Predicted Values', color='orange', linestyle='--')
    plt.title(f'{model_name}: Predicted vs Actual')
    plt.legend()
    plt.show()
    return rmse, mae, mape, r2

