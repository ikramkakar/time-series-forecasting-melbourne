import numpy as np
import pandas as pd

# ==========================================
# PREPROCESSING & SLIDING WINDOWS FOR LSTM
# ==========================================

# 1. Define look-back window size (e.g., using the past 7 days to predict the next day)
look_back = 7

def create_sliding_windows(data, look_back):
    X, y = [], []
    for i in range(len(data) - look_back):
        X.append(data[i:(i + look_back)])
        y.append(data[i + look_back])
    return np.array(X), np.array(y)

# 2. Generate tabular windows from your original 'series' vector
values = series.values
X_all, y_all = create_sliding_windows(values, look_back)

# 3. Sequential Timeline Split (Matches your 70% / 15% / 15% temporal split)
train_split = int(len(X_all) * 0.70)
val_split = int(len(X_all) * 0.85)

X_train, y_train = X_all[:train_split], y_all[:train_split]
X_val, y_val = X_all[train_split:val_split], y_all[train_split:val_split]
X_test, y_test = X_all[val_split:], y_all[val_split:]

# 4. Reshape inputs to 3D Tensor format required by Keras LSTM: (samples, time_steps, features)
X_train = np.reshape(X_train, (X_train.shape[0], X_train.shape[1], 1))
X_val = np.reshape(X_val, (X_val.shape[0], X_val.shape[1], 1))
X_test = np.reshape(X_test, (X_test.shape[0], X_test.shape[1], 1))

print("--- Sliding Window Matrices Created Successfully ---")
