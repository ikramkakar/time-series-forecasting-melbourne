import numpy as np
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense

# ==========================================
# 13. PROBABILISTIC FORECASTING VIA PINBALL LOSS
# ==========================================

# Explicitly define pinball loss to ensure Keras tracking is preserved
def get_pinball_loss(q):
    def pinball_loss(y_true, y_pred):
        # Cast inputs to float32 to prevent mixed-type tensor conflicts
        y_true = tf.cast(y_true, tf.float32)
        y_pred = tf.cast(y_pred, tf.float32)
        error = y_true - y_pred
        return tf.reduce_mean(tf.maximum(q * error, (q - 1) * error), axis=-1)
    return pinball_loss

# Ensure look_back is defined from your previous preprocessing cells
# (If it isn't defined, it usually defaults to your look_back sequence length, e.g., 7 or 30)
if 'look_back' not in locals():
    look_back = X_train.shape[1]

# --- Lower Quantile Model (2.5%) ---
model_q_low = Sequential([
    LSTM(32, input_shape=(look_back, 1)),
    Dense(1)
])
model_q_low.compile(optimizer='adam', loss=get_pinball_loss(0.025))
print("Training lower quantile model...")
model_q_low.fit(X_train, y_train, epochs=5, batch_size=32, verbose=0)

# --- Upper Quantile Model (97.5%) ---
model_q_high = Sequential([
    LSTM(32, input_shape=(look_back, 1)),
    Dense(1)
])
model_q_high.compile(optimizer='adam', loss=get_pinball_loss(0.975))
print("Training upper quantile model...")
model_q_high.fit(X_train, y_train, epochs=5, batch_size=32, verbose=0)

# --- Generate Predictions ---
preds_low = model_q_low.predict(X_test).flatten()
preds_high = model_q_high.predict(X_test).flatten()

# Flatten test targets for direct numpy boolean array comparison
y_test_flat = y_test.flatten()

# --- Interval Evaluation Metrics ---
picp = np.mean((y_test_flat >= preds_low) & (y_test_flat <= preds_high)) * 100
